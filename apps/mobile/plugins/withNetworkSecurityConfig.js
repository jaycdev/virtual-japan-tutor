// Lets the app trust certificates the user installs on the phone, such as a self-signed or
// private CA for a self-hosted server (ADR-0013).
//
// Android apps that target API 24+ ignore user-installed CAs unless they opt in with a network
// security config. This plugin writes one that trusts the system CAs and the user CAs, keeps
// cleartext (plain http://) blocked, and points the manifest at it. It is applied to every build.
const path = require("node:path");
const fs = require("node:fs");
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require("@expo/config-plugins");

const RESOURCE = "network_security_config";

function networkSecurityConfigXml() {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withNetworkSecurityConfig.js (ADR-0013). Do not edit by hand. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors>
            <certificates src="system" />
            <certificates src="user" />
        </trust-anchors>
    </base-config>
</network-security-config>
`;
}

/** Points the application element at the network security config resource. Mutates and returns it. */
function setNetworkSecurityConfig(application) {
  application.$ = application.$ || {};
  application.$["android:networkSecurityConfig"] = `@xml/${RESOURCE}`;
  return application;
}

const withNetworkSecurityConfig = (config) => {
  config = withDangerousMod(config, [
    "android",
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, "app", "src", "main", "res", "xml");
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${RESOURCE}.xml`), networkSecurityConfigXml());
      return cfg;
    },
  ]);
  return withAndroidManifest(config, (cfg) => {
    setNetworkSecurityConfig(AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults));
    return cfg;
  });
};

module.exports = withNetworkSecurityConfig;
module.exports.networkSecurityConfigXml = networkSecurityConfigXml;
module.exports.setNetworkSecurityConfig = setNetworkSecurityConfig;
