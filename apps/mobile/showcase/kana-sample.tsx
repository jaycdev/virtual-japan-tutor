import Svg, { Path, Rect } from 'react-native-svg';
import { useCSSVariable } from 'uniwind';

/**
 * Dev-only demo of a themed SVG asset (issue #43, item 9): uniwind's
 * useCSSVariable resolves the --color-pitch design token at render, so the
 * same asset re-colours with the light/dark theme instead of shipping
 * variants. (Tried first: fill="context-fill" - web inline SVG only, and
 * currentColor - react-native-svg on Android renders black. Verified on
 * device: useCSSVariable is the native-safe route.)
 * Shape: a stylised torii - simple hand-authored geometry. The production app
 * icon (the 読 glyph) is generated by scripts/generate-icon.mjs into
 * assets/brand/.
 */
export function KanaSample({ size = 64 }: { size?: number }) {
  const pitch = useCSSVariable('--color-pitch');
  return (
    <Svg width={size} height={size} viewBox="0 0 100 100" fill={pitch}>
      {/* top curved lintel (kasagi) */}
      <Path d="M6 18 Q50 8 94 18 L90 26 Q50 17 10 26 Z" fill={pitch} />
      {/* second lintel (nuki) */}
      <Rect x="16" y="32" width="68" height="7" fill={pitch} />
      {/* centre plaque (gakuzuka) */}
      <Rect x="46" y="26" width="8" height="12" fill={pitch} />
      {/* left pillar */}
      <Path d="M22 39 L29 39 L31 92 L20 92 Z" fill={pitch} />
      {/* right pillar */}
      <Path d="M71 39 L78 39 L80 92 L69 92 Z" fill={pitch} />
    </Svg>
  );
}
